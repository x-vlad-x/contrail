#!/usr/bin/env python3
"""Embed Telegram's call sounds for the Qt-free media library."""
import pathlib
import sys

source = pathlib.Path(sys.argv[1])
output = pathlib.Path(sys.argv[2])
parts = ["// Generated by tools/td-call-sounds.py.\n#pragma once\n"]
for name, file in (("Incoming", "incoming"), ("Outgoing", "outgoing"),
                   ("Connecting", "connect"), ("Ended", "end"), ("Busy", "busy")):
    data = (source / f"call_{file}.mp3").read_bytes()
    parts.append(f"inline constexpr unsigned char k{name}[] = {{\n")
    for offset in range(0, len(data), 16):
        parts.append("  " + ",".join(f"0x{b:02x}" for b in data[offset:offset + 16]) + ",\n")
    parts.append("};\n")
text = "".join(parts)
output.parent.mkdir(parents=True, exist_ok=True)
if not output.exists() or output.read_text() != text:
    output.write_text(text)

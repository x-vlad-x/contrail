#!/usr/bin/env python3
"""Writes gtk-ui/td/strings_en.inc: the English value of every string the interface uses.

They are what a first start without a network shows. Run it when a new key appears in gtk-ui:
    tools/td-strings.py [path/to/lang.strings]
Every key listed is also what the program asks TDLib for in the user's language.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "tdesktop/Telegram/Resources/langs/lang.strings"
OUTPUT = ROOT / "gtk-ui/td/strings_en.inc"


def main() -> None:
    used = set()
    for path in ROOT.joinpath("gtk-ui").rglob("*"):
        if path.suffix in {".cpp", ".hpp"}:
            used.update(re.findall(r'\blng_[a-z0-9_]+', path.read_text(encoding="utf-8")))
    known: dict[str, dict[str, str]] = {}
    for key, form, value in re.findall(r'^"(lng_[a-z0-9_]+)(#\w+)?"\s*=\s*"((?:[^"\\]|\\.)*)";', SOURCE.read_text(encoding="utf-8"), re.M):
        known.setdefault(key, {})[form.lstrip("#") or "value"] = value
    missing = sorted(key for key in used if key not in known)
    if missing:
        raise SystemExit(f"not in {SOURCE}: {' '.join(missing)}")
    lines = ["// Generated by tools/td-strings.py.\n"]
    for key in sorted(used):
        forms = known[key]
        if "value" in forms:
            lines.append(f'{{"{key}", "{forms["value"]}", nullptr}},\n')
        else:
            lines.append(f'{{"{key}", "{forms["other"]}", "{forms.get("one", forms["other"])}"}},\n')
    OUTPUT.write_text("".join(lines), encoding="utf-8")
    print(f"{len(used)} strings")


if __name__ == "__main__":
    main()
